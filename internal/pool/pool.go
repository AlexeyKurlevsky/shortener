// Package pool предоставляет generic-пул объектов, поддерживающих
// сброс состояния через метод Reset(). В основе лежит sync.Pool:
// объекты переиспользуются, а перед возвратом в пул их состояние
// сбрасывается.
package pool

import "sync"

// Resettable — ограничение generic-параметра: тип обязан уметь
// сбрасывать своё состояние методом Reset().
//
// Обычно этому интерфейсу удовлетворяет указатель на структуру,
// для которой утилита resetgen сгенерировала метод с приёмником-указателем,
// например *Buffer. Именно такие типы и стоит подставлять в T.
type Resettable interface {
	Reset()
}

// Pool — generic-контейнер для объектов одного конкретного типа T.
// Внутри использует sync.Pool для повторного использования «тяжёлых»
// объектов и освобождения их от давления на GC.
type Pool[T Resettable] struct {
	pool sync.Pool
}

// New создаёт Pool и настраивает фабрику для создания новых объектов.
// Фабрика вызывается каждый раз, когда Get() обращается к пустому пулу,
// поэтому конструктор принимает её как обязательный параметр.
func New[T Resettable](factory func() T) *Pool[T] {
	return &Pool[T]{
		pool: sync.Pool{
			New: func() any {
				return factory()
			},
		},
	}
}

// Get возвращает объект из пула. Если пул пуст, объект создаётся
// через фабрику, переданную в New. Возвращаемый объект всегда готов
// к использованию (его состояние — «нулевое»).
func (p *Pool[T]) Get() T {
	return p.pool.Get().(T)
}

// Put сбрасывает состояние объекта и возвращает его в пул.
// Метод Reset() вызывается на самом объекте, поэтому тип T должен
// его реализовывать (см. ограничение Resettable).
func (p *Pool[T]) Put(v T) {
	v.Reset()
	p.pool.Put(v)
}
